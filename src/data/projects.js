export function getProjectBySlug(slug) {
  return projects.find((p) => p.slug === slug || (p.aliases && p.aliases.includes(slug)));
}

export function getAdjacentProjects(currentSlug) {
  const index = projects.findIndex((p) => p.slug === currentSlug || (p.aliases && p.aliases.includes(currentSlug)));
  if (index === -1) return { prev: null, next: null };
  const prev = projects[(index - 1 + projects.length) % projects.length];
  const next = projects[(index + 1) % projects.length];
  return { prev, next };
}
